import java.util.Scanner;

public class Composite {

    public static void main(String[] args) {
        Scanner sc= new Scanner(System.in);

        for(int j=0;j<100;j++){
            int i=2;
        while(i<j){
            if(j%i==0){
                System.out.println(j);
                break;
            }
            i++;


        }
        }
        sc.close();
        
    }
    
}
